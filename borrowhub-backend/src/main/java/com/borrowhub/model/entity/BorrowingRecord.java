package com.borrowhub.model.entity;

import com.borrowhub.model.enums.BorrowingStatus;
import com.borrowhub.model.enums.PhysicalCondition;
import jakarta.persistence.*;
import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

import java.time.Instant;
import java.time.LocalDate;

@Entity
@Table(name = "borrowing_records")
public class BorrowingRecord {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "transaction_code", nullable = false, unique = true, length = 50)
    private String transactionCode;

    @Column(name = "idempotency_key", unique = true, length = 64)
    private String idempotencyKey;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "reservation_id", nullable = false)
    private Reservation reservation;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "user_id", nullable = false)
    private User user;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "resource_id", nullable = false)
    private Resource resource;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "resource_unit_id")
    private ResourceUnit resourceUnit;

    @Column(name = "quantity_issued", nullable = false)
    private int quantityIssued = 1;

    @Column(name = "quantity_returned", nullable = false)
    private int quantityReturned = 0;

    @Column(name = "quantity_damaged", nullable = false)
    private int quantityDamaged = 0;

    @Column(name = "quantity_lost", nullable = false)
    private int quantityLost = 0;

    // Generated Stored Column in MySQL (C17)
    @Generated(event = EventType.INSERT)
    @Column(name = "quantity_outstanding", insertable = false, updatable = false)
    private int quantityOutstanding = 1;

    // C40/C42: Authoritative Database Date generated by MySQL DEFAULT (CURRENT_DATE)
    @Generated(event = EventType.INSERT)
    @Column(name = "issue_date", insertable = false, updatable = false)
    private LocalDate issueDate;

    @Column(name = "due_date", nullable = false)
    private LocalDate dueDate;

    @Column(name = "actual_return_date")
    private LocalDate actualReturnDate;

    @Column(name = "closed_at")
    private Instant closedAt;

    @Enumerated(EnumType.STRING)
    @Column(name = "condition_at_issue", nullable = false, length = 20)
    private PhysicalCondition conditionAtIssue = PhysicalCondition.GOOD;

    @Enumerated(EnumType.STRING)
    @Column(name = "condition_at_return", length = 20)
    private PhysicalCondition conditionAtReturn;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "issued_by", nullable = false)
    private User issuedBy;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "returned_to")
    private User returnedTo;

    @Enumerated(EnumType.STRING)
    @Column(name = "previous_status", length = 20)
    private BorrowingStatus previousStatus;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private BorrowingStatus status = BorrowingStatus.ACTIVE;

    @Column(columnDefinition = "TEXT")
    private String remarks;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt = Instant.now();

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt = Instant.now();

    @PrePersist
    protected void onCreate() {
        if (createdAt == null) createdAt = Instant.now();
        if (updatedAt == null) updatedAt = Instant.now();
    }

    @PreUpdate
    protected void onUpdate() {
        updatedAt = Instant.now();
    }

    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getTransactionCode() { return transactionCode; }
    public void setTransactionCode(String transactionCode) { this.transactionCode = transactionCode; }

    public String getIdempotencyKey() { return idempotencyKey; }
    public void setIdempotencyKey(String idempotencyKey) { this.idempotencyKey = idempotencyKey; }

    public Reservation getReservation() { return reservation; }
    public void setReservation(Reservation reservation) { this.reservation = reservation; }

    public User getUser() { return user; }
    public void setUser(User user) { this.user = user; }

    public Resource getResource() { return resource; }
    public void setResource(Resource resource) { this.resource = resource; }

    public ResourceUnit getResourceUnit() { return resourceUnit; }
    public void setResourceUnit(ResourceUnit resourceUnit) { this.resourceUnit = resourceUnit; }

    public int getQuantityIssued() { return quantityIssued; }
    public void setQuantityIssued(int quantityIssued) { this.quantityIssued = quantityIssued; }

    public int getQuantityReturned() { return quantityReturned; }
    public void setQuantityReturned(int quantityReturned) { this.quantityReturned = quantityReturned; }

    public int getQuantityDamaged() { return quantityDamaged; }
    public void setQuantityDamaged(int quantityDamaged) { this.quantityDamaged = quantityDamaged; }

    public int getQuantityLost() { return quantityLost; }
    public void setQuantityLost(int quantityLost) { this.quantityLost = quantityLost; }

    public int getQuantityOutstanding() { return quantityOutstanding; }
    public void setQuantityOutstanding(int quantityOutstanding) { this.quantityOutstanding = quantityOutstanding; }

    public LocalDate getIssueDate() { return issueDate; }
    // Protected or internal setter for tests if needed, but not called during standard flow

    public LocalDate getDueDate() { return dueDate; }
    public void setDueDate(LocalDate dueDate) { this.dueDate = dueDate; }

    public LocalDate getActualReturnDate() { return actualReturnDate; }
    public void setActualReturnDate(LocalDate actualReturnDate) { this.actualReturnDate = actualReturnDate; }

    public Instant getClosedAt() { return closedAt; }
    public void setClosedAt(Instant closedAt) { this.closedAt = closedAt; }

    public PhysicalCondition getConditionAtIssue() { return conditionAtIssue; }
    public void setConditionAtIssue(PhysicalCondition conditionAtIssue) { this.conditionAtIssue = conditionAtIssue; }

    public PhysicalCondition getConditionAtReturn() { return conditionAtReturn; }
    public void setConditionAtReturn(PhysicalCondition conditionAtReturn) { this.conditionAtReturn = conditionAtReturn; }

    public User getIssuedBy() { return issuedBy; }
    public void setIssuedBy(User issuedBy) { this.issuedBy = issuedBy; }

    public User getReturnedTo() { return returnedTo; }
    public void setReturnedTo(User returnedTo) { this.returnedTo = returnedTo; }

    public BorrowingStatus getPreviousStatus() { return previousStatus; }
    public void setPreviousStatus(BorrowingStatus previousStatus) { this.previousStatus = previousStatus; }

    public BorrowingStatus getStatus() { return status; }
    public void setStatus(BorrowingStatus status) { this.status = status; }

    public String getRemarks() { return remarks; }
    public void setRemarks(String remarks) { this.remarks = remarks; }

    public Instant getCreatedAt() { return createdAt; }
    public void setCreatedAt(Instant createdAt) { this.createdAt = createdAt; }

    public Instant getUpdatedAt() { return updatedAt; }
    public void setUpdatedAt(Instant updatedAt) { this.updatedAt = updatedAt; }
}
